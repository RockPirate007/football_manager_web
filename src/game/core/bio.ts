const GROWTH_CLUBS = ["Атлетико", "Порту", "Зальцбург", "Аякс", "Бенфика", "Гент", "Монако", "Ланс"];

/** Высота по позиции (см) */
function heightFor(pos: Position): number {
  const base = pos === "ВРТ" ? 191 : pos === "ЗАЩ" ? 184 : pos === "ПЗ" ? 179 : 180;
  return Math.round(gauss(base, 5));
}

/** Рабочая нога */
function pickFoot(): PlayerBio["foot"] {
  const roll = Math.random();
  if (roll < 0.72) return "Правая";
  if (roll < 0.92) return "Левая";
  return "Обе";
}

/**
 * Собрать биографию: путь «академия → 1–2 клуба → текущий клуб».
 * clubName — текущий клуб игрока.
 */
export function makeBio(nation: string, pos: Position, age: number, clubName: string): PlayerBio {
  const academies = ACADEMY_CLUBS[nation] ?? ACADEMY_CLUBS["Англия"];
  const steps: string[] = [];

  if (age <= 20) {
    steps.push(`воспитанник «${choice(academies)}»`);
  } else {
    const youth = choice(academies);
    const startYear = Math.max(2015, 2025 - (age - 16) - randint(0, 2));
    steps.push(`«${youth}» (${startYear}–${startYear + randint(1, 3)})`);
    if (age >= 23 && Math.random() < 0.7) {
      const bridge = choice(GROWTH_CLUBS);
      const y1 = startYear + randint(2, 4);
      steps.push(`«${bridge}» (${y1}–${Math.min(2025, y1 + randint(1, 3))})`);
    }
  }
  steps.push(`«${clubName}» (с 2024)`);

  return {
    real: false,
    nation,
    height: heightFor(pos),
    foot: pickFoot(),
    career: steps.join(" → "),
    honours: age <= 20 ? "" : "",
    traits: choice(TRAITS[pos]),
  };
}

/** Биография по умолчанию (миграция старых сейвов) */
export function defaultBio(nation = "Англия"): PlayerBio {
  return {
    real: false,
    nation,
    height: 180,
    foot: "Правая",
    career: "",
    honours: "",
    traits: "",
  };
}
