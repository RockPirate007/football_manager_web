/** Выбрать страну по весам. Вторые дивизионы (eng2) берут пул страны (eng) */
export function pickNation(leagueId?: string): string {
  const base = leagueId ? leagueId.replace(/2$/, "") : undefined;
  const weights = base ? LEAGUE_NATION_WEIGHTS[base] ?? GLOBAL_NATION_WEIGHTS : GLOBAL_NATION_WEIGHTS;
  const valid = weights.filter(([n]) => (NATION_POOLS[n]?.first.length ?? 0) > 0);
  const total = valid.reduce((s, [, w]) => s + w, 0);
  let roll = Math.random() * total;
  for (const [nation, w] of valid) {
    roll -= w;
    if (roll <= 0) return nation;
  }
  return valid[0][0];
}
